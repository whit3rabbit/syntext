/// True if `word` (already lowercased) is an English stopword.
pub(crate) fn is_stopword(word: &str) -> bool {
    STOPWORDS.binary_search(&word).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn stopwords_are_sorted() {
        assert!(STOPWORDS.windows(2).all(|w| w[0] < w[1]));
    }

    #[test]
    fn lookups() {
        assert!(is_stopword("the"));
        assert!(is_stopword("which"));
        assert!(!is_stopword("new"));
        assert!(!is_stopword("query"));
        assert!(!is_stopword("The"), "input must be lowercased first");
    }
}
